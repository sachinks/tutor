"""Gemini chat provider with Ollama embeddings for the Tutor AI service."""

import logging
import time
from collections.abc import AsyncIterator

import httpx
from google import genai
from google.genai import types


from .base import (
    EmbeddingKind,
    Message,
    ProviderError,
    ProviderTimeout,
    ProviderUnavailable,
)
from .ollama import OllamaProvider

logger = logging.getLogger("tutor_ai.providers.gemini")


class GeminiProvider:
    """Use Gemini for chat and Ollama for text embeddings."""

    name = "gemini"

    def __init__(
        self,
        *,
        api_key: str,
        chat_model: str,
        ollama: OllamaProvider,
        timeout_seconds: float = 120.0,
    ) -> None:
        self.chat_model = chat_model
        self._ollama = ollama

        self._client = genai.Client(
            api_key=api_key,
            http_options=types.HttpOptions(
                timeout=int(timeout_seconds * 1000),
            ),
        )

        # Embeddings are still generated by Ollama.
        self.embedding_model = ollama.embedding_model
        self.dimensions = ollama.dimensions

    def _convert_messages(
        self,
        messages: list[Message],
    ) -> tuple[str | None, list[types.Content]]:
        """Convert Tutor AI messages into Gemini's content format."""

        system_parts: list[str] = []
        contents: list[types.Content] = []

        for message in messages:
            if message.role == "system":
                system_parts.append(message.content)
                continue

            role = "model" if message.role == "assistant" else "user"

            contents.append(
                types.Content(
                    role=role,
                    parts=[types.Part(text=message.content)],
                )
            )

        system_instruction = (
            "\n\n".join(system_parts) if system_parts else None
        )

        return system_instruction, contents

    async def chat(
        self,
        messages: list[Message],
        *,
        max_tokens: int,
        temperature: float,
    ) -> AsyncIterator[str]:
        """Stream generated text from Gemini."""

        started = time.perf_counter()
        first_text_logged = False
        system_instruction, contents = self._convert_messages(messages)

        config = types.GenerateContentConfig(
            system_instruction=system_instruction,
            max_output_tokens=max_tokens,
            temperature=temperature,
        )

        try:
            request_started = time.perf_counter()
            stream = await self._client.aio.models.generate_content_stream(
                model=self.chat_model,
                contents=contents,
                config=config,
            )
            logger.info(
                "Gemini stream opened",
                extra={"open_duration_ms": round((time.perf_counter() - request_started) * 1000, 1)},
            )

            async for chunk in stream:
                text = chunk.text

                if text:
                    if not first_text_logged:
                        first_text_logged = True
                        logger.info(
                            "Gemini first text received",
                            extra={"time_to_first_text_ms": round((time.perf_counter() - started) * 1000, 1)},
                        )
                    yield text
            logger.info(
                "Gemini stream completed",
                extra={"duration_ms": round((time.perf_counter() - started) * 1000, 1), "received_text": first_text_logged},
            )

        except Exception as exc:
            # Do not expose API keys or raw authentication details.
            status_code = getattr(exc, "code", None)
            status_code = status_code() if callable(status_code) else status_code

            if isinstance(exc, TimeoutError) or isinstance(
                exc, httpx.TimeoutException
            ):
                raise ProviderTimeout(
                    "Gemini request timed out.",
                    provider=self.name,
                ) from exc

            if status_code == 429:
                raise ProviderUnavailable(
                    "Gemini rate limit or quota reached.",
                    provider=self.name,
                ) from exc

            if status_code in (401, 403):
                raise ProviderUnavailable(
                    "Gemini authentication failed or access was denied.",
                    provider=self.name,
                ) from exc

            if isinstance(exc, ProviderError):
                raise

            raise ProviderUnavailable(
                "Gemini request failed. Check the model, API key, "
                "network connection, and provider quota.",
                provider=self.name,
            ) from exc

    async def embed(
        self,
        texts: list[str],
        *,
        kind: EmbeddingKind,
    ) -> list[list[float]]:
        """Delegate embeddings to the existing Ollama provider."""

        return await self._ollama.embed(texts, kind=kind)

    async def health(self) -> bool:
        """Check Ollama health and whether Gemini can answer a small request."""

        try:
            if not await self._ollama.health():
                return False

            response = await self._client.aio.models.generate_content(
                model=self.chat_model,
                contents="Reply with OK.",
                config=types.GenerateContentConfig(
                    max_output_tokens=5,
                    temperature=0,
                ),
            )

            return bool(response.text)

        except Exception:
            return False

    async def aclose(self) -> None:
        """Close both provider clients."""

        try:
            await self._client.aio.aclose()
        finally:
            await self._ollama.aclose()